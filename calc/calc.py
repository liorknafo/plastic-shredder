def endurance(Su, d_mm):
    """Marin-corrected rotating-bending endurance limit (machined, 90 % reliability)."""
    ka = 4.51 * Su ** -0.265
    kb = 1.24 * d_mm ** -0.107
    return 0.5 * min(Su, 1400) * ka * kb * 0.897


