def winkler(T):
    """Clearance-aware estimate: flank overlap u(s) = s*theta - clr for s > s0 = clr/theta;
    T = 6 t k ∫ (s θ − c) s ds over [s0, l]. Returns (theta, s0, p_edge)."""
    lo, hi = theta0, theta0 * 50
    for _ in range(80):
        th = (lo + hi) / 2
        s0 = clr / th
        tq = 6 * P.T_BLADE * k_w * (th * (l_h ** 3 - s0 ** 3) / 3 - clr * (l_h ** 2 - s0 ** 2) / 2)
        lo, hi = (th, hi) if tq < T * 1000 else (lo, th)
    return th, clr / th, k_w * (l_h * th - clr)


