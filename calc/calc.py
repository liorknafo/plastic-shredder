def all_cases(mat, T_op, T_lim):
    res = []
    for label, a, b in SHARES:
        for sh in ("A", "B"):
            if sh == "B" and b == 0:
                continue
            res.append(("Operating, " + label, sh, True, worst(sh, a * T_op, b * T_op, mat, True)))
    for label, a, b in SHARES:
        for sh in ("A", "B"):
            if sh == "B" and b == 0:
                continue
            res.append(("Jam, " + label, sh, False, worst(sh, a * T_lim, b * T_lim, mat, False)))
    return res


def min_sf(mat, T, fatigue):
    sfs = []
    for label, a, b in SHARES:
        for sh in ("A", "B"):
            if sh == "B" and b == 0:
                continue
            sfs.append(worst(sh, a * T, b * T, mat, fatigue)["sf"])
    return min(sfs)


def allowable(mat, fatigue):
    need = P.FATIGUE_SF if fatigue else P.STATIC_SF
    lo, hi = 1.0, 400.0
    if min_sf(mat, lo, fatigue) < need:
        return 0.0
    for _ in range(22):
        mid = (lo + hi) / 2
        if min_sf(mat, mid, fatigue) >= need:
            lo = mid
        else:
            hi = mid
    return lo


