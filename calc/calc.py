# End cap: ANNULAR plate (hole b = 5.25), outer edge simply supported on the Ø25 bore edge of the
# clamped face (a = 12.5), inner edge free, screw-head load as a line load at r0 = 6.6 (middle of the
# head's bearing ring 5.25..8). Axisymmetric Kirchhoff plate, solved exactly (4 constants).
def annular_plate_max_stress(W, t, b, a, r0, nu=0.3):
    k = W / (2 * math.pi)       # all terms scaled by the plate stiffness D, which cancels in the stress
    def mr(r, outer):
        # Mr/D = theta' + nu*theta/r as (coefficients of A1, A2, C1, C2), constant
        if not outer:
            return [(1 + nu), -(1 - nu) / r ** 2, 0, 0], 0.0
        part = k * ((math.log(r) / 2 + 0.25) + nu * (math.log(r) / 2 - 0.25))
        return [0, 0, (1 + nu), -(1 - nu) / r ** 2], part
    rows, rhs = [], []
    co, cst = mr(b, False); rows.append(co); rhs.append(-cst)
    co, cst = mr(a, True); rows.append(co); rhs.append(-cst)
    rows.append([r0, 1 / r0, -r0, -1 / r0]); rhs.append(k * (r0 * math.log(r0) / 2 - r0 / 4))
    ci, si = mr(r0, False); co, so = mr(r0, True)
    rows.append([ci[j] - co[j] for j in range(4)]); rhs.append(so - si)
    Mx = [rows[i] + [rhs[i]] for i in range(4)]
    for i in range(4):
        piv = max(range(i, 4), key=lambda q: abs(Mx[q][i])); Mx[i], Mx[piv] = Mx[piv], Mx[i]
        for q in range(4):
            if q != i:
                f = Mx[q][i] / Mx[i][i]
                Mx[q] = [x - f * y for x, y in zip(Mx[q], Mx[i])]
    A1, A2, C1, C2 = (Mx[i][4] / Mx[i][i] for i in range(4))
    best = 0.0
    for j in range(401):
        r = b + (a - b) * j / 400
        if r <= r0:
            th, dth = A1 * r + A2 / r, A1 - A2 / r ** 2
        else:
            th = C1 * r + C2 / r + k * (r * math.log(r) / 2 - r / 4)
            dth = C1 - C2 / r ** 2 + k * (math.log(r) / 2 + 0.25)
        best = max(best, abs(dth + nu * th / r), abs(th / r + nu * dth))
    return 6 * best / t ** 2


